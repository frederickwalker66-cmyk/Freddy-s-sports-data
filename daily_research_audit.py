"""Daily research-quality report: does not train, score, or alter Champion-001.

Input is the current untrusted research odds file and fail-closed quarantine.
Historical outcomes or model probabilities must not be inferred from prices.
"""
import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
import json
from pathlib import Path


def summarize(rows, validation):
    if not isinstance(validation, dict):
        raise ValueError("Missing Challenger audit")
    if validation.get("observations") != len(rows):
        raise ValueError("Input differs from validation report")
    if validation.get("quarantined") != len(rows):
        raise ValueError("Unverified records were promoted")
    if any(validation.get(k) != 0 for k in (
            "staged_for_research_only", "bet_ready_selections",
            "certified_challenger_predictions", "certified_champion_001_predictions",
            "automated_bets_placed", "independently_reverified_sportsbook_prices")):
        raise ValueError("Research-only invariant violated")
    if validation.get("champion_001_modified") is not False:
        raise ValueError("Frozen model invariant violated")
    by_league = Counter()
    by_market = Counter()
    rejected_by_reason = validation.get("quarantine_causes", {})
    seen = set()
    duplicate_ids = 0
    for row in rows:
        if not isinstance(row, dict) or row.get("certified_prediction") is not False or row.get("model_probability") is not None:
            raise ValueError("Invalid evidence promoted as model probability")
        by_league[str(row.get("league", "unknown"))] += 1
        by_market[str(row.get("market_type", "unknown"))] += 1
        key = (row.get("id"), row.get("timestamp"), row.get("line"), row.get("odds_american"))
        if key in seen:
            duplicate_ids += 1
        seen.add(key)
    return {
        "report_type": "daily_research_quality_not_model_training",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "source": "sportsgameodds_v2",
        "total_odds_observations": len(rows),
        "by_league": dict(sorted(by_league.items())),
        "by_market": dict(sorted(by_market.items())),
        "duplicate_quote_keys": duplicate_ids,
        "validation_rejection_causes": rejected_by_reason,
        "quarantine_count": validation["quarantined"],
        "independently_verified_outcomes": 0,
        "certified_shadow_predictions": 0,
        "learned_model_updates": 0,
        "independent_model_probabilities_generated": 0,
        "production_model_changed": False,
        "learning_blockers": [
            "No independently adjudicated outcomes linked to this provider's game/player IDs",
            "No pregame Champion-001 model probabilities generated by frozen model",
            "No complete official roster/injury/lineup/price crosswalk",
            "No demonstrated out-of-sample validation or calibration"
        ],
        "recommendation": "Archive evidence and improve validation. Do not retrain or promote Champion-001."
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--odds", required=True)
    parser.add_argument("--validation", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    with Path(args.odds).open(encoding="utf-8") as stream:
        rows = [json.loads(line) for line in stream if line.strip()]
    validation = json.loads(Path(args.validation).read_text(encoding="utf-8"))
    report = summarize(rows, validation)
    dst = Path(args.output)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
